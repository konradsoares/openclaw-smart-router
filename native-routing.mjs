import {PairInventory,estimateTokens,selectNativeModels} from './routing-policy.mjs';

export const LANGUAGE_INSTRUCTION=[
 'RESPONSE LANGUAGE: Write all natural-language answer text in the language requested by the CURRENT user message. If there is no explicit language request, use the language of the latest user message (the CURRENT user message). Do not copy the language of previous assistant replies. This applies equally to Colab and PAIR. Keep quoted literals, code, commands, and identifiers unchanged.',
 'PROJECT CONTEXT: Smart Router is an OpenClaw plugin that selects between local inference through PAIR and a separate Google Colab GPU-backed inference provider. Colab provides GPU compute when that backend is selected and available; it is not an API for fetching arbitrary facts about the user. Use conversation history for user-specific details, never fabricate project status.',
 'Operational status/progress notices generated by the routing plugin are in English. This exception does not apply to normal assistant answers.'
].join('\n');

export function createNativeRouting({cfg={},inventory=new PairInventory(),logger=console}={}){
 const history=new Map();
 function capture(event,ctx){
   if(!ctx?.sessionKey||!Array.isArray(event?.messages))return;
   let sum=0;
   for(const msg of event.messages){
     if(typeof msg?.content==='string')sum+=estimateTokens(msg.content);
     else if(Array.isArray(msg?.content))for(const item of msg.content)if(typeof item?.text==='string')sum+=estimateTokens(item.text);
   }
   history.delete(ctx.sessionKey);
   history.set(ctx.sessionKey,Math.min(sum,250000));
   if(history.size>256)history.delete(history.keys().next().value);
 }
 async function resolve(event,ctx){
   const routes=cfg.nativeRouting||{};
   if(cfg.telegramMode!=='native'||routes.enabled!==true||ctx?.agentId!==(cfg.cloudAgent||'main')||!(ctx?.channelId==='telegram'||(String(ctx?.channelId??'').length>0 && (cfg.allowedTelegramIds||[]).map(String).includes(String(ctx?.channelId)))))return undefined;
   let available;
   try {available=await inventory.get(routes.pairModelsUrl||'http://127.0.0.1:8080/v1/models');}
   catch(err){logger.warn('[smart-router] PAIR inventory unavailable: '+String(err.message).slice(0,120));available=new Map();}
   const input=String(event?.prompt||'');
   const forcedCommand=routes.forceCommandsEnabled===true?(/^\s*!(pair|colab)(?:\s|$)/i.exec(input)?.[1]?.toLowerCase()||null):null;
   const historyTokens=history.get(ctx?.sessionKey)??routes.unknownHistoryTokens??1024;
   let decision=selectNativeModels({prompt:input,historyTokens,config:cfg,inventory:available});
   if(forcedCommand==='pair'){
     const pairModel=(routes.localModels||[]).find(p=>available.has(p.model?.slice(7))&&p.model?.startsWith('nvpair/'))?.model;
     const localOnly=selectNativeModels({prompt:input,historyTokens,
       config:{...cfg,nativeRouting:{...routes,localModels:(routes.localModels||[]).filter(p=>p.model===pairModel),colabModel:''}},
       inventory:available});
     decision={...localOnly,reason:'forced-pair'};
   }
   if(forcedCommand==='colab'){
     const colabOnly=selectNativeModels({prompt:input,historyTokens,
       config:{...cfg,nativeRouting:{...routes,localModels:[]}},
       inventory:new Map()});
     decision={...colabOnly,reason:'forced-colab'};
     if(decision.model && !decision.model.startsWith('colab/'))decision={...decision,model:null,fallbacks:[],reason:'forced-colab-ineligible'};
   }
   let model=decision.model;
   if(!model){
     // Fail closed: never leave the default paid model selected by accident.
     const first=routes.localModels?.[0]?.model;
     model=first&&first.startsWith('nvpair/')?first:'nvpair/__no_eligible_model__';
     logger.warn('[smart-router] no eligible model; forcing local-only failure');
   }
   const slash=model.indexOf('/');
   logger.info('[smart-router] native-model-route model='+model+' reason='+decision.reason+' estimatedTokens='+decision.required);
   return {providerOverride:model.slice(0,slash),modelOverride:model.slice(slash+1),fallbacksOverride:decision.fallbacks};
 }
 function promptContext(event,ctx){
   capture(event,ctx);
   if(ctx?.agentId!==(cfg.cloudAgent||'main')&&ctx?.agentId!==(cfg.localAgent||'pair'))return undefined;
   return {appendSystemContext:LANGUAGE_INSTRUCTION};
 }
 return {resolve,promptContext};
}
